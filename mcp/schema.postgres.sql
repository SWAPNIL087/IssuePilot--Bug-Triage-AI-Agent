-- The tool server's database user: exactly what the runbooks need, nothing more.
-- No DELETE, no DDL, no other tables, no other columns. Check it with: python -m triageguard.actions.permcheck
CREATE ROLE triageguard_mcp LOGIN PASSWORD 'CHANGE-ME-PASSWORD';
GRANT USAGE ON SCHEMA public TO triageguard_mcp;
GRANT SELECT (order_id, customer_email, status, updated_at) ON orders TO triageguard_mcp;
GRANT UPDATE (status, updated_at)                           ON orders TO triageguard_mcp;
GRANT INSERT ON order_status_history, agent_audit TO triageguard_mcp;