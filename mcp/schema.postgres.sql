-- Postgres schema (Neon, Supabase or any Postgres): tables, sample data and a least-privilege role.
-- Run in the Neon SQL Editor. Before running, replace CHANGE-ME-PASSWORD with a long random password.

CREATE TABLE orders (
    order_id       TEXT PRIMARY KEY,
    customer_email TEXT NOT NULL,
    status         TEXT NOT NULL CHECK (status IN ('Pending', 'Invoiced', 'Completed')),
    updated_at     TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE order_status_history (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id    TEXT NOT NULL,
    old_status  TEXT NOT NULL,
    new_status  TEXT NOT NULL,
    changed_by  TEXT NOT NULL,
    request_id  TEXT NOT NULL,
    changed_at  TIMESTAMPTZ NOT NULL DEFAULT now()
);

-- Append-only. request_id is the primary key, so a request can never run twice.
CREATE TABLE agent_audit (
    request_id      TEXT PRIMARY KEY,
    ticket_id       TEXT NOT NULL,
    runbook_id      TEXT NOT NULL,
    runbook_version INTEGER NOT NULL,
    runbook_hash    TEXT NOT NULL,
    requester_email TEXT NOT NULL,
    order_id        TEXT NOT NULL,
    old_status      TEXT NOT NULL,
    new_status      TEXT NOT NULL,
    outcome         TEXT NOT NULL,
    created_at      TIMESTAMPTZ NOT NULL DEFAULT now()
);

